local kanso_status, kanso = pcall(require, "kanso")
if not kanso_status then
  return {}
end

vim.cmd("colorscheme kanso")

kanso.setup({
  theme = 'mist',
  -- Remove bold and/or italic tokens
  keywordStyle   = { italic = false, bold = false },
  statementStyle = { italic = false, bold = false },
  commentStyle   = { italic = false, bold = false },
  constantStyle  = { italic = false, bold = false },
  overrides = function(colors)
    return {
      CursorLineNr               = { fg = colors.palette.yellow3, bold = false },
      MatchParen                 = { bold = false },
      Boolean                    = { fg = colors.palette.yellow3, bold = false },
      WinSeparator               = { fg = colors.palette.mistBg2 },
      FzfLuaBorder               = { fg = colors.palette.mistBg2 },
      IblIndent                  = { fg = colors.palette.mistBg2 },
      NvimTreeIndentMarker       = { fg = colors.palette.misgBg2 },
      ["@variable.builtin"]      = { italic = false },
      ["@keyword.operator"]      = { bold = false },
      ["@keyword.return"]        = { bold = false },
      ["@string.documentation.python"] = { link = "Comment" }
    }
  end
})

local kolors = require("kanso.colors").setup()

-- Both tabline and statusline colors are only defined if a colorscheme is loaded,
-- in this case, kanso.
local tabline_colors = {
  separator    = { fg = kolors.paletteyellow3, bold = true },
  active_tab   = { fg = kolors.palette.fg, bold = true },
  inactive_tab = { fg = kolors.palette.mistBg3,    bold = false }
}

return {
  tabline_colors = tabline_colors,
  statusline_colors = nil
}
